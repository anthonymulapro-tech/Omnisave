// Listen for messages from the React popup
chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
    if (request.action === 'FAST_SAVE') {

        chrome.tabs.query({ active: true, currentWindow: true }, async (tabs) => {
            const activeTab = tabs[0];

            if (activeTab) {
                const pageUrl = activeTab.url;
                const userToken = request.token;

                try {
                    console.log("1. Requesting AI Preview for:", pageUrl);

                    // --- STEP 1: CALL PREVIEW ENDPOINT (AI Analysis) ---
                    const previewResponse = await fetch('http://localhost:5000/api/links/preview', {
                        method: 'POST',
                        headers: {
                            'Content-Type': 'application/json',
                            'Authorization': `Bearer ${userToken}`
                        },
                        body: JSON.stringify({ url: pageUrl })
                    });

                    if (!previewResponse.ok) {
                        throw new Error(`AI Analysis failed with status ${previewResponse.status}`);
                    }

                    const previewData = await previewResponse.json();
                    console.log("AI Analysis completed:", previewData);

                    // --- STEP 2: CALL SAVE ENDPOINT (Database Insertion) ---
                    console.log("2. Saving to database with AI tags/categories...");
                    const saveResponse = await fetch('http://localhost:5000/api/links', {
                        method: 'POST',
                        headers: {
                            'Content-Type': 'application/json',
                            'Authorization': `Bearer ${userToken}`
                        },
                        body: JSON.stringify({
                            url: previewData.url,
                            title: previewData.title,
                            thumbnail_url: previewData.thumbnail_url,
                            platform: previewData.platform,
                            categories: previewData.categories, // Generated by AI
                            tags: previewData.tags              // Generated by AI
                        })
                    });

                    if (!saveResponse.ok) {
                        throw new Error(`Database save failed with status ${saveResponse.status}`);
                    }

                    console.log("Successfully saved to Omnisave!");

                    // --- TRIGGER SYSTEM NOTIFICATION ---
                    chrome.notifications.create({
                        type: "basic",
                        iconUrl: "test.png",
                        title: "Omnisave - Fast-Save",
                        message: `Saved & Categorized: ${previewData.title}`
                    });

                    // --- STEP 3: SUCCESS FEEDBACK ---
                    sendResponse({
                        success: true,
                        message: "Saved & Categorized! ✅"
                    });

                } catch (error) {
                    console.error("Fast-Save Error:", error);

                    chrome.notifications.create({
                        type: "basic",
                        iconUrl: "icons.svg",
                        title: "Omnisave - Error",
                        message: "Failed to save the link. Check your connection."
                    });

                    sendResponse({
                        success: false,
                        error: "Error: " + error.message
                    });
                }
            } else {
                sendResponse({ success: false, error: "Could not read active tab." });
            }
        });

        // Return true to indicate we will respond asynchronously
        return true;
    }
});